const { app, BrowserWindow, session } = require('electron')
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
app.setPath('userData', path.join(__dirname, 'isolated-data')); app.disableHardwareAcceleration()
const deadline = setTimeout(() => app.exit(1), 25000)
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
async function until(fn) { for (let i = 0; i < 100; i++) { if (await fn()) return; await wait(25) } throw new Error('Condition timed out') }
app.whenReady().then(async () => {
  // Hard stop for any unexpected outgoing request, in addition to fake fetch.
  session.defaultSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_request, callback) => callback({ cancel: true }))
  const win = new BrowserWindow({ width: 1080, height: 920, show: false, webPreferences: { contextIsolation: true, nodeIntegration: false } })
  win.webContents.on('console-message', (_event, level, message) => { if (level >= 3) console.error('Fixture renderer:', message) })
  const js = code => win.webContents.executeJavaScript(code).catch(error => { console.error('Fixture expression:', code); throw error })
  const ai = `document.querySelector('section[aria-labelledby="ai-panel-title"]')`
  const magic = `document.querySelector('section[aria-labelledby]:has([role=group][aria-label="사용 방식"])')`
  const mcp = `document.querySelector('section[aria-labelledby="mcp-panel-title"]')`
  const save = section => `${section}.querySelector('[data-settings-save-footer] button')`
  const input = (selector, value) => js(`{const el=${selector};Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}));}`)
  await win.loadFile(path.join(__dirname, 'index.html')); win.show()
  await until(() => js(`!!${ai} && document.querySelectorAll('[data-settings-save-footer]').length===3`))
  await wait(700)
  assert.equal(await js('window.qa.writes.length'), 0)
  for (const section of [ai, magic, mcp]) assert.equal(await js(`${save(section)}.disabled`), true)
  assert.equal(await js('document.getElementById("ai-response-language-value").textContent'), '피프노트 언어에 맞춤')
  await js(`${ai}.querySelectorAll('[role=option]')`)
  await js(`Array.from(${ai}.querySelectorAll('button')).find(el=>el.textContent==='OpenAI').click()`)
  await input(`${ai}.querySelector('input[type=password]')`, 'edited-fixture-key')
  await input('document.getElementById("ai-context-length")', '4096')
  await js('document.getElementById("ai-response-language").click()')
  await until(() => js('!!document.querySelector("[role=listbox][aria-labelledby=ai-response-language-label]")'))
  assert.equal(await js('document.querySelectorAll("[role=listbox][aria-labelledby=ai-response-language-label] [role=option]").length'), 26)
  await js('Array.from(document.querySelectorAll("[role=option]")).find(el=>el.textContent==="Français").click()')
  await js(`Array.from(${magic}.querySelectorAll('button')).find(el=>el.textContent==='AI API').click()`)
  await until(() => js(`${magic}.querySelector('.settings-select-trigger').textContent.includes('Qwen')`))
  await js(`${magic}.querySelector('.settings-select-trigger').click()`)
  await until(() => js(`!!${magic}.querySelector('[role=listbox]')`))
  await js(`${magic}.querySelector('[role=option]').click()`)
  await js(`${mcp}.querySelector('[role=switch][aria-label="연결 허용"]').click()`)
  await js(`${mcp}.querySelector('[role=switch][aria-label="메모 저장 알림"]').click()`)
  await js(`Array.from(${mcp}.querySelectorAll('button')).find(el=>el.textContent==='Claude Code').click()`)
  assert.equal(await js('localStorage.getItem("openpeepnote_mcp_client")'), null)
  await js('window.dispatchEvent(new Event("blur"));document.getElementById("settings-tab-general").click()')
  await wait(700)
  await js('document.getElementById("settings-tab-ai").click()')
  assert.equal(await js('window.qa.writes.length'), 0, 'editing, blur and tab navigation must not save these sections')
  assert.equal(await js('window.qa.mcp.enabled'), false)
  await js(`${save(magic)}.click()`)
  await until(() => js('window.qa.writes.length===1'))
  assert.deepEqual(await js('Object.keys(window.qa.writes[0].body)'), ['magic_pen'])
  assert.equal(await js('window.qa.settings.ai_provider'), 'qwen')
  await js('window.qa.failNext=true')
  await js(`${save(ai)}.click()`)
  await until(() => js(`!!${ai}.querySelector('[role=alert]')`))
  await wait(650)
  assert.equal(await js('window.qa.writes.length'), 2, 'failed saves must wait for explicit retry')
  assert.equal(await js('window.qa.settings.ai_provider'), 'qwen')
  await js(`${save(ai)}.click()`)
  await until(() => js('window.qa.settings.ai_response_language==="fr"'))
  assert.equal(await js('window.qa.settings.ai_provider'), 'openai')
  assert.equal(await js('window.qa.settings.language'), 'ko')
  assert.equal(await js('window.qa.writes[2].body.magic_pen'), undefined)
  assert.equal(await js('window.qa.settings.openai_api_key'), 'edited-fixture-key')
  await js(`${save(mcp)}.click()`)
  await until(() => js('window.qa.mcp.enabled===true'))
  assert.equal(await js('window.qa.mcp.notificationsEnabled'), false)
  assert.deepEqual(await js('window.qa.writes[3]'), { path: '/api/mcp', body: { enabled: true, notificationsEnabled: false } })
  assert.equal(await js('localStorage.getItem("openpeepnote_mcp_client")'), 'claude-code')
  await js('document.getElementById("settings-tab-general").click()')
  await js('document.querySelector("[role=switch][aria-labelledby=fixed-start-date-label]").click()')
  await until(() => js('window.qa.writes.length===5'))
  assert.deepEqual(await js('Object.keys(window.qa.writes[4].body)'), ['fixed_start_date'])
  await js('document.getElementById("settings-tab-ai").click()')
  await input(`${ai}.querySelector('input[type=password]')`, 'unsaved-fixture-key')
  await js('window.qa.unmount()')
  await wait(700)
  assert.equal(await js('window.qa.writes.length'), 5, 'unmount must not flush manual drafts')
  await js('window.qa.mount()')
  await until(() => js('document.getElementById("ai-response-language-value")?.textContent==="Français"'))
  assert.equal(await js('window.qa.settings.openai_api_key'), 'edited-fixture-key')
  fs.writeFileSync('/tmp/peepnote-manual-settings.png', (await win.webContents.capturePage()).toPNG())
  clearTimeout(deadline); console.log('SETTINGS_QA_SUCCESS independent explicit saves, no blur/navigation/unmount autosave, failed-save retry, MCP preferences, response language, general autosave')
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
