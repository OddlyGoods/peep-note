const { app, BrowserWindow, session } = require('electron')
const path = require('node:path'), assert = require('node:assert/strict')
app.setPath('userData', path.join(__dirname, 'isolated-data')); app.disableHardwareAcceleration()
const deadline = setTimeout(() => app.exit(1), 10000)
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
app.whenReady().then(async () => {
  session.defaultSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_request, cb) => cb({ cancel: true }))
  const win = new BrowserWindow({ show: false, webPreferences: { contextIsolation: true, nodeIntegration: false } })
  const js = code => win.webContents.executeJavaScript(code)
  const until = async code => { for (let i = 0; i < 100; i++) { if (await js(code)) return; await wait(20) } throw new Error('Quick List timed out: ' + code) }
  await win.loadFile(path.join(__dirname, 'index.html'))
  await until('window.qa?.ready')
  assert.equal(await js('document.getElementById("root").textContent'), '', 'loading does not draw an empty-state panel')
  assert.deepEqual(await js('window.qa.results'), [], 'mounting a hidden list must not create a toast')
  await js('window.qa.open(1,"empty")')
  await until('window.qa.results.length===1')
  assert.deepEqual(await js('window.qa.results[0]'), { request: 1, status: 'empty' })
  assert.equal(await js('document.getElementById("root").textContent'), '', 'no-records text is shown only in the shared desktop toast')
  assert.equal(win.isVisible(), false)
  await js('window.qa.open(2,"notes")')
  await until('window.qa.results.length===2 && document.body.textContent.includes("Quick List fixture")')
  assert.deepEqual(await js('window.qa.results[1]'), { request: 2, status: 'ready' })
  await js('window.qa.open(3,"deferred")')
  await until('!!window.qa.release')
  await js('window.qa.open(4,"empty")')
  await until('window.qa.results.length===3')
  await js('window.qa.release()'); await wait(80)
  assert.deepEqual(await js('window.qa.results[2]'), { request: 4, status: 'empty' })
  assert.equal(await js('window.qa.results.length'), 3, 'a stale request cannot reopen the list')
  await js('window.qa.open(5,"error")')
  await until('window.qa.results.length===4')
  assert.deepEqual(await js('window.qa.results[3]'), { request: 5, status: 'error' }, 'a failed request is not reported as an empty list')
  win.destroy(); clearTimeout(deadline); console.log('QUICK_LIST_QA_SUCCESS: hidden loading, empty result, first open, real notes, stale response and failure'); app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
